package com.zendesk.maxwell.monitoring;

import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class MaxwellDiagnosticContext {

	public final Config config;
	public final List<MaxwellDiagnostic> diagnostics;

	public MaxwellDiagnosticContext(Config config, List<MaxwellDiagnostic> diagnostics) {
		this.config = config;
		this.diagnostics = diagnostics;
	}

	public static class Config {
		public static final long DEFAULT_MIN_INTERVAL_MS = 5000L;
		public static final String DEFAULT_KAFKA_TOPIC = "maxwell_diagnostic";
		private static final Pattern INTERPOLATION = Pattern.compile("%\\{[^}]*\\}");

		public boolean enable;
		public long timeout;

		/**
		 * bearer token required to call /diagnostic. When null, only loopback callers are
		 * served, and they get a redacted response (no resources or error details).
		 */
		public String token;

		/**
		 * minimum time between two diagnostic runs; requests in between get the cached result
		 */
		public long minInterval = DEFAULT_MIN_INTERVAL_MS;

		/**
		 * kafka topic the producer diagnostic probe is sent to (never the CDC topic)
		 */
		public String kafkaTopic = DEFAULT_KAFKA_TOPIC;

		/**
		 * @return true if {@link #kafkaTopic} is, or may expand to, a topic generated by the given
		 * (possibly %{db}/%{table}/%{type} interpolated) topic template
		 */
		public boolean kafkaTopicMayMatch(String topicTemplate) {
			if (kafkaTopic == null || topicTemplate == null) {
				return false;
			}
			StringBuilder regex = new StringBuilder();
			Matcher m = INTERPOLATION.matcher(topicTemplate);
			int last = 0;
			while (m.find()) {
				regex.append(Pattern.quote(topicTemplate.substring(last, m.start()))).append(".+");
				last = m.end();
			}
			regex.append(Pattern.quote(topicTemplate.substring(last)));
			return kafkaTopic.matches(regex.toString());
		}

		public boolean isTokenRequired() {
			return token != null && !token.isEmpty();
		}
	}
}
